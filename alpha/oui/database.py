class OuiDatabase:
    """Manages OUI lookups with fallback to embedded dataset, database, and LAA detection."""

    def __init__(self, db_path: Optional[Path] = None):
        self.db_path = db_path
        self.memory_cache: Dict[str, str] = dict(EMBEDDED_OUI_MAP)
        if self.db_path and self.db_path.exists():
            self._load_from_sqlite()

    def _load_from_sqlite(self) -> None:
        """Load additional custom or updated OUIs from local SQLite table."""
        try:
            conn = sqlite3.connect(str(self.db_path))
            cur = conn.cursor()
            cur.execute("SELECT prefix, manufacturer FROM oui_prefixes")
            for prefix, manufacturer in cur.fetchall():
                self.memory_cache[prefix.upper()] = manufacturer
            conn.close()
        except Exception:
            pass

    def lookup(self, mac_address: Optional[str]) -> Tuple[str, str]:
        """
        Lookup manufacturer and normalized OUI prefix for a MAC address.
        
        Returns:
            (manufacturer_name, oui_prefix)
            If randomized: ("[Randomized / Private MAC]", "RANDOMIZED")
            If unknown: ("UNKNOWN", prefix)
        """
        if not mac_address:
            return "UNKNOWN", "UNKNOWN"
        
        normalized = sanitize_mac(mac_address)
        if normalized == "00:00:00:00:00:00":
            return "UNKNOWN", "UNKNOWN"
        
        # Check if locally administered / randomized
        if is_randomized_mac(normalized):
            return "[Randomized / Private MAC]", "RANDOMIZED"
        
        # Standard 24-bit OUI prefix (first 3 octets)
        prefix_24 = normalized[:8]
        if prefix_24 in self.memory_cache:
            return self.memory_cache[prefix_24], prefix_24
        
        # 28-bit OUI (first 9 chars, e.g. 70:B3:D5:E)
        prefix_28 = normalized[:10]
        if prefix_28 in self.memory_cache:
            return self.memory_cache[prefix_28], prefix_28
            
        # 36-bit OUI (first 13 chars)
        prefix_36 = normalized[:13]
        if prefix_36 in self.memory_cache:
            return self.memory_cache[prefix_36], prefix_36
            
        return "UNKNOWN", prefix_24


# Module-level singleton
_default_oui_db: Optional[OuiDatabase] = None


def get_oui_database(db_path: Optional[Path] = None) -> OuiDatabase:
    """Get or initialize global OUI database singleton."""
    global _default_oui_db
    if _default_oui_db is None:
        _default_oui_db = OuiDatabase(db_path=db_path)
    return _default_oui_db


def lookup_vendor(mac: str) -> Tuple[str, str]:
    """Convenience helper to lookup manufacturer for a MAC address."""
    return get_oui_database().lookup(mac)
